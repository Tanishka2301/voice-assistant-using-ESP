# ============================================================
# 1. IMPORT REQUIRED LIBRARIES
# ============================================================

import sounddevice as sd
# Captures live sound from the microphone.

import numpy as np
# Helps process numerical audio data, including volume.

from scipy.io.wavfile import write
# Saves recorded audio into a WAV file.

import whisper
# Converts speech/audio into written text (Speech-to-Text).

from google import genai
# Provides access to Google's Gemini generative AI API.

import pyttsx3
# Converts text into speech (Text-to-Speech).


# ============================================================
# 2. CONNECT TO GEMINI
# ============================================================

client = genai.Client(api_key="")
# Creates a Gemini API client.
# The API key authenticates the application with Google.
# Insert your valid API key here before running the program.


# ============================================================
# 3. LOAD THE WHISPER MODEL
# ============================================================

print("Loading Whisper...")

model = whisper.load_model("base")
# Loads the Whisper "base" speech-recognition model.
# The model runs locally on the laptop.
# Audio is processed by Whisper to recognize spoken words.

print("Whisper is ready!")


# ============================================================
# 4. INITIALIZE TEXT-TO-SPEECH
# ============================================================

engine = pyttsx3.init()
# Initializes the text-to-speech engine.
# It will speak the answers generated by Gemini.


# ============================================================
# 5. CONFIGURE AUDIO RECORDING
# ============================================================

sample_rate = 16000
# Audio is sampled 16,000 times per second.
# This is a suitable sample rate for Whisper.

block_duration = 0.1
# Each audio block represents 0.1 seconds (100 milliseconds).

block_size = int(sample_rate * block_duration)
# Calculates samples in one block.
# 16,000 * 0.1 = 1,600 samples per block.

threshold = 500
# Volume threshold used to detect the beginning of speech.
# A volume above 500 is treated as voice activity.

silence_limit = 5.0
# The recording stops after 5 seconds of detected silence.

silence_blocks_needed = int(silence_limit / block_duration)
# Calculates how many silent blocks make 5 seconds.
# 5.0 / 0.1 = 50 blocks.


# ============================================================
# 6. START THE CONTINUOUS ASSISTANT LOOP
# ============================================================

while True:
# Repeats the entire voice-assistant process indefinitely.
# The loop stops only when a break statement is executed.

    print("\n--------------------------------")
    print("Waiting for your voice...")
    print("--------------------------------")

    recorded_audio = []
    # Empty list to store recorded audio blocks.

    voice_started = False
    # Indicates whether the program has detected speech.

    silence_blocks = 0
    # Counts consecutive blocks classified as silence.


    # ========================================================
    # 7. OPEN THE MICROPHONE STREAM
    # ========================================================

    with sd.InputStream(
        samplerate=sample_rate,
        channels=1,
        dtype="int16",
        blocksize=block_size
    ) as stream:
    # Opens a microphone input stream.
    # samplerate=16000: captures 16,000 samples per second.
    # channels=1: records mono audio (one channel).
    # dtype="int16": stores samples as 16-bit integers.
    # blocksize=1600: reads 0.1 seconds of audio per block.
    # "with" manages the stream and closes it when the block ends.

        while True:
        # Keeps reading audio until 5 seconds of silence
        # are detected after speech has started.

            audio, overflowed = stream.read(block_size)
            # Reads the next 1,600 audio samples.
            # audio contains the microphone samples.
            # overflowed indicates whether an audio buffer
            # overflow occurred during the read.

            volume = np.max(np.abs(audio))
            # Converts negative sample values to positive values.
            # Finds the largest absolute sample in this block.
            # This is a simple peak-volume measurement.


            # ------------------------------------------------
            # 8. WAIT UNTIL SPEECH IS DETECTED
            # ------------------------------------------------

            if not voice_started:
            # Executes this section while speech has not started.

                if volume > threshold:
                # Checks whether the peak volume exceeds 500.

                    print("VOICE DETECTED!")
                    print("Recording started...\n")

                    voice_started = True
                    # Changes the state to indicate that recording
                    # has started.

                    recorded_audio.append(audio.copy())
                    # Stores a copy of the first detected audio block.

                continue
                # Goes to the next iteration of the inner loop.
                # Before speech starts, audio blocks below the
                # threshold are not stored.


            # ------------------------------------------------
            # 9. STORE AUDIO AFTER SPEECH STARTS
            # ------------------------------------------------

            recorded_audio.append(audio.copy())
            # Adds the current audio block to the recording.
            # Audio continues to be stored during speech and silence.


            if volume > threshold:
            # Checks whether this block contains sufficiently
            # loud sound according to the selected threshold.

                silence_blocks = 0
                # Resets the silence counter when sound is detected.

            else:
                # Runs when the block is classified as silence.

                silence_blocks += 1
                # Increases the consecutive-silence counter by one.

                silence_time = silence_blocks * block_duration
                # Converts the number of silent blocks into seconds.

                print(
                    f"Silence: {silence_time:.1f} / "
                    f"{silence_limit:.1f} seconds"
                )
                # Displays the current silence duration.
                # Example: Silence: 2.3 / 5.0 seconds.


                # --------------------------------------------
                # 10. STOP RECORDING AFTER 5 SECONDS
                # --------------------------------------------

                if silence_blocks >= silence_blocks_needed:
                # Checks whether 50 consecutive silent blocks
                # have been counted.

                    print("\n5 seconds of silence detected.")
                    print("Recording stopped.")

                    break
                    # Exits the inner while loop.
                    # The microphone stream then closes.
                    # The outer assistant loop will continue later.


    # ========================================================
    # 11. COMBINE AND SAVE THE RECORDED AUDIO
    # ========================================================

    audio_data = np.concatenate(recorded_audio)
    # Combines all stored audio blocks into one continuous array.

    write(
        "recording.wav",
        sample_rate,
        audio_data
    )
    # Saves the combined audio as recording.wav.
    # The file contains the audio samples at 16,000 Hz.

    print("\nSaved as: recording.wav")


    # ========================================================
    # 12. WHISPER: SPEECH-TO-TEXT
    # ========================================================

    print("\nConverting speech to text...")

    result = model.transcribe("recording.wav")
    # Passes the saved audio file to Whisper.
    # Whisper recognizes the spoken words and returns a result.

    question = result["text"].strip()
    # Extracts the recognized text from the result dictionary.
    # strip() removes spaces and newline characters at the ends.

    print("\nYou said:")
    print(question)
    # Displays what Whisper understood.


    # ========================================================
    # 13. CHECK THE EXIT COMMAND
    # ========================================================

    if question.lower() in ["exit", "quit", "stop"]:
    # Converts the recognized text to lowercase and checks
    # whether it exactly matches one of these commands.

        print("\nGoodbye!")

        break
        # Exits the outer while loop and ends the assistant.


    # ========================================================
    # 14. SEND THE QUESTION TO GEMINI
    # ========================================================

    print("\nGemini is thinking...")

    response = client.models.generate_content(
        model="gemini-3.6-flash",
        contents=question
    )
    # Sends the recognized question to the Gemini API.
    # model specifies the Gemini model to use.
    # contents contains the user's question.
    # The API returns a generated response.

    answer = response.text
    # Extracts the text answer from Gemini's response.

    print("\nGemini:")
    print(answer)
    # Displays Gemini's answer in the terminal.


    # ========================================================
    # 15. CLEAN THE ANSWER BEFORE SPEAKING
    # ========================================================

    spoken_answer = answer.replace("*", "")
    # Removes asterisks, often used for Markdown formatting.

    spoken_answer = spoken_answer.replace("#", "")
    # Removes hash symbols used in Markdown headings.

    spoken_answer = spoken_answer.replace("_", "")
    # Removes underscores used for formatting.

    spoken_answer = spoken_answer.replace("`", "")
    # Removes backticks used for code formatting.


    # ========================================================
    # 16. TEXT-TO-SPEECH: SPEAK THE ANSWER
    # ========================================================

    print("\nSpeaking...")

    engine.say(spoken_answer)
    # Adds the cleaned answer to the speech engine's queue.

    engine.runAndWait()
    # Processes the speech queue and waits until speaking ends.

    print("Finished.")
    # Indicates that the response has finished speaking.

# Reaches the next iteration of the outer while loop.
# The assistant starts waiting for the next voice input.
